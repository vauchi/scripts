# Pins the core invariant of vet-autofix.sh: exemption auto-sync must NEVER
# commit a Cargo.lock change. A lockfile diff means a real dependency version
# moved — that belongs in a reviewed bump MR, not a tidy: auto-sync. If it
# slips through, the auto-sync MR can break consumer tests and wedge open
# forever (relay 2026-07-21). The script must fail loud and leave Cargo.lock
# uncommitted.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCRIPT="$SCRIPT_DIR/../ci/vet-autofix.sh"

ws=$(mktemp -d)
trap 'rm -rf "$ws"' EXIT

mkdir -p "$ws/bin" "$ws/repo/supply-chain"

cat >"$ws/repo/supply-chain/config.toml" <<'TOML'
[policy.fixture]
audit-as-crates-io = true
TOML

cat >"$ws/repo/Cargo.lock" <<'LOCK'
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "demo"
version = "0.1.0"
LOCK

# cargo mock: `vet` fails on the first check (forcing the auto-fix path), then
# `regenerate exemptions` "fixes" vetting BUT also drifts Cargo.lock — the
# exact smuggled-dep-bump the guard must catch. Subsequent `vet` passes so the
# only thing standing between the mock and a commit is the lockfile guard.
cat >"$ws/bin/cargo" <<'CARGO_MOCK'
#!/usr/bin/env bash
printf 'cargo %s\n' "$*" >>"$CARGO_LOG"
case "$*" in
    "vet regenerate exemptions")
        printf '\n[[exemptions.demo]]\nversion = "0.1.0"\ncriteria = "safe-to-deploy"\n' \
            >>supply-chain/config.toml
        # Simulate a dependency bump leaking into the lockfile.
        printf '\n[[package]]\nname = "sneaky-bump"\nversion = "9.9.9"\n' >>Cargo.lock
        ;;
    "vet --locked")
        # Fail the first check (no marker yet), pass once regenerate ran.
        grep -q 'exemptions.demo' supply-chain/config.toml
        exit $?
        ;;
    "vet fmt") : ;;
esac
exit 0
CARGO_MOCK
chmod +x "$ws/bin/cargo"

git -C "$ws/repo" init --quiet
git -C "$ws/repo" config user.name test
git -C "$ws/repo" config user.email test@example.invalid
git -C "$ws/repo" add Cargo.lock supply-chain/config.toml
git -C "$ws/repo" commit --quiet -m baseline

set +e
output=$(
    cd "$ws/repo"
    PATH="$ws/bin:/usr/bin:/bin" \
        CARGO_LOG="$ws/cargo.log" \
        CI_COMMIT_BRANCH="main" \
        CI_DEFAULT_BRANCH="main" \
        "$SCRIPT" 2>&1
)
status=$?
set -e

fail=0

if [[ $status -eq 0 ]]; then
    printf 'FAIL guard did not fail loud on Cargo.lock drift (exit 0)\n%s\n' "$output" >&2
    fail=1
fi

if ! printf '%s' "$output" | grep -q 'Cargo.lock changed during exemption sync'; then
    printf 'FAIL expected the lockfile-guard message\n%s\n' "$output" >&2
    fail=1
fi

# The script must never `cargo generate-lockfile` (the removed bump vector).
if grep -q 'generate-lockfile' "$ws/cargo.log"; then
    printf 'FAIL script invoked cargo generate-lockfile\n' >&2
    fail=1
fi

# HEAD must still be the baseline commit — nothing committed.
if [[ "$(git -C "$ws/repo" rev-list --count HEAD)" -ne 1 ]]; then
    printf 'FAIL guard committed despite lockfile drift\n' >&2
    fail=1
fi

if [[ $fail -ne 0 ]]; then
    exit 1
fi

printf 'PASS Cargo.lock drift fails loud and is never committed\n'
