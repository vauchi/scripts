# Regression test for source exemption sync. A consumer whose cargo-vet
# exemptions are already minimal must stay unchanged when the source project
# contains exemptions for dependencies that the consumer does not use.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCRIPT="$SCRIPT_DIR/../ci/vet-autofix.sh"

ws=$(mktemp -d)
trap 'rm -rf "$ws"' EXIT

mkdir -p "$ws/bin" "$ws/repo/supply-chain"

cat >"$ws/repo/supply-chain/config.toml" <<'TOML'
[policy.fixture]
audit-as-crates-io = true

[[exemptions.syn]]
version = "2.0.119"
criteria = "safe-to-deploy"
TOML
cp "$ws/repo/supply-chain/config.toml" "$ws/original-config.toml"

cat >"$ws/source-config.toml" <<'TOML'
[[exemptions.core-only-dependency]]
version = "1.0.0"
criteria = "safe-to-deploy"

[[exemptions.syn]]
version = "2.0.119"
criteria = "safe-to-deploy"
TOML

cat >"$ws/repo/Cargo.lock" <<'LOCK'
# This file is automatically @generated by Cargo.
version = 4
LOCK

cat >"$ws/bin/curl" <<'CURL_MOCK'
#!/usr/bin/env bash
cat "$SOURCE_CONFIG_PATH"
CURL_MOCK
chmod +x "$ws/bin/curl"

cat >"$ws/bin/cargo" <<'CARGO_MOCK'
#!/usr/bin/env bash
printf 'cargo %s\n' "$*" >>"$CARGO_LOG"
case "$*" in
    "vet regenerate exemptions")
        cp "$ORIGINAL_CONFIG_PATH" supply-chain/config.toml
        ;;
esac
exit 0
CARGO_MOCK
chmod +x "$ws/bin/cargo"

git -C "$ws/repo" init --quiet
git -C "$ws/repo" config user.name test
git -C "$ws/repo" config user.email test@example.invalid
git -C "$ws/repo" add Cargo.lock supply-chain/config.toml
git -C "$ws/repo" commit --quiet -m baseline

set +e
output=$(
    cd "$ws/repo"
    PATH="$ws/bin:/usr/bin:/bin" \
        SOURCE_CONFIG_PATH="$ws/source-config.toml" \
        ORIGINAL_CONFIG_PATH="$ws/original-config.toml" \
        CARGO_LOG="$ws/cargo.log" \
        CI_API_V4_URL="https://gitlab.example/api/v4" \
        CI_COMMIT_BRANCH="test-branch" \
        CI_DEFAULT_BRANCH="main" \
        "$SCRIPT" --sync-from=77874344 2>&1
)
status=$?
set -e

if [[ $status -ne 0 ]]; then
    printf 'FAIL sync exited %s\n%s\n' "$status" "$output" >&2
    exit 1
fi

if ! cmp -s "$ws/original-config.toml" "$ws/repo/supply-chain/config.toml"; then
    printf 'FAIL sync restored source-only exemptions to the consumer\n' >&2
    git -C "$ws/repo" diff -- supply-chain/config.toml >&2
    exit 1
fi

if ! git -C "$ws/repo" diff --quiet -- supply-chain/config.toml; then
    printf 'FAIL sync left a cargo-vet config diff\n' >&2
    exit 1
fi

printf 'PASS source-only exemptions are pruned before persistence\n'
