"""The advisory scan reports tracked candidates, coverage, and failures."""

import json
import subprocess
import unittest
from pathlib import Path

from quality_scan_fixture import ScanFixture


class QualityScanTests(ScanFixture):
    def test_tracks_root_and_child_repositories_without_scanning_untracked_files(self):
        core = self.init_repo(self.root / "core")
        self.tracked(self.root, "root.py", "value = 1\n")
        self.tracked(core, "tests/value.rs", "#[test]\nfn value() { assert!(true); }\n")
        (core / "untracked.rs").write_text("todo!();\n")
        data = self.report()
        self.assertTrue(data["advisory"])
        self.assertEqual([r["name"] for r in data["repositories"]], ["root", "core"])
        self.assertEqual(data["scanned_files"], 2)
        self.assertEqual(data["candidate_count"], 1)
        self.assertEqual(data["candidates"], [{
            "rule": "literal-tautology", "path": "core/tests/value.rs",
            "line": 2, "test_like_file": True,
        }])
        row = data["repositories"][1]
        self.assertEqual(row["head"], self.git(core, "rev-parse", "HEAD"))
        self.assertTrue(row["dirty"])

    def test_supports_a_named_repository_without_other_repository_findings(self):
        core = self.init_repo(self.root / "core")
        other = self.init_repo(self.root / "other")
        self.tracked(core, "src/lib.rs", "fn value() { todo!(); }\n")
        self.tracked(other, "src/lib.rs", "fn value() { unimplemented!(); }\n")
        data = self.report("core")
        self.assertEqual([r["name"] for r in data["repositories"]], ["core"])
        self.assertEqual([(x["rule"], x["path"]) for x in data["candidates"]],
                         [("placeholder", "core/src/lib.rs")])

    def test_reports_literal_empty_sync_and_async_tests(self):
        self.tracked(self.root, "tests/empty.rs", "#[test]\nfn sync() {}\n"
                     "#[tokio::test]\nasync fn asynchronous() {}\n")
        data = self.report()
        self.assertEqual([(x["rule"], x["line"]) for x in data["candidates"]],
                         [("empty-rust-test", 1), ("empty-rust-test", 3)])

    def test_presence_candidates_cover_call_expressions_and_messages(self):
        self.tracked(self.root, "tests/values.rs", "assert!(foo().is_ok());\n"
                     'assert!(result.is_some(), "required");\n')
        data = self.report()
        self.assertEqual([(x["rule"], x["line"]) for x in data["candidates"]],
                         [("presence-assertion", 1), ("presence-assertion", 2)])

    def test_a_specific_assertion_does_not_automatically_suppress_a_candidate(self):
        self.tracked(self.root, "tests/value.rs", "assert!(result.is_ok());\n"
                     "assert_eq!(result.unwrap(), 3);\n")
        self.assertEqual(self.report()["candidate_count"], 1)

    def test_plain_negative_controls_are_not_findings(self):
        self.tracked(self.root, "tests/value.rs", "assert_eq!(actual, expected);\n"
                     "assert!(is_valid);\nlet result = operation()?;\n")
        self.assertEqual(self.report()["candidates"], [])

    def test_generated_examples_do_not_exclude_handwritten_generators(self):
        self.tracked(self.root, "generator.py", '#!/usr/bin/env python3\n'
                     'template = "# Auto-generated file"\nraise NotImplementedError\n')
        self.tracked(self.root, "Tokens.cs", "// Auto-generated by tokens.py\nTODO();\n")
        data = self.report()
        self.assertEqual(data["scanned_files"], 1)
        self.assertEqual(data["repositories"][0]["excluded"],
                         [{"path": "Tokens.cs", "reason": "generated-first-line"}])
        self.assertEqual(data["candidates"][0]["path"], "generator.py")

    def test_symlinks_are_reported_without_following_external_source(self):
        outside = Path(self.temp.name) / "outside.rs"
        outside.write_text("todo!();\n")
        (self.root / "link.rs").symlink_to(outside)
        self.git(self.root, "add", "link.rs")
        data = self.report()
        self.assertEqual(data["candidates"], [])
        self.assertEqual(data["repositories"][0]["excluded"],
                         [{"path": "link.rs", "reason": "symlink"}])

    def test_deleted_tracked_source_fails_instead_of_reporting_a_clean_scan(self):
        self.tracked(self.root, "missing.py", "print(1)\n").unlink()
        result = self.run_scan("--json")
        self.assertEqual(result.returncode, 2)
        self.assertEqual(result.stdout, "")
        self.assertIn("missing.py", result.stderr)

    def test_replaced_parent_symlink_cannot_scan_external_source(self):
        path = self.tracked(self.root, "src/lib.rs", "fn real() {}\n")
        path.unlink()
        path.parent.rmdir()
        outside = Path(self.temp.name) / "external"
        outside.mkdir()
        (outside / "lib.rs").write_text("todo!();\n")
        (self.root / "src").symlink_to(outside, target_is_directory=True)
        data = self.report()
        self.assertEqual(data["candidates"], [])
        self.assertEqual(data["repositories"][0]["excluded"],
                         [{"path": "src/lib.rs", "reason": "symlink"}])

    def test_unknown_or_external_repository_is_an_error(self):
        for name in ["unknown", "../outside"]:
            with self.subTest(name=name):
                result = self.run_scan(name)
                self.assertEqual(result.returncode, 2)
                self.assertIn("Unknown repository", result.stderr)

    def test_invalid_git_repository_does_not_disappear_from_coverage(self):
        broken = self.root / "broken"
        (broken / ".git").mkdir(parents=True)
        result = self.run_scan()
        self.assertEqual(result.returncode, 2)
        self.assertIn("broken", result.stderr)

    def test_inline_tests_are_candidates_but_production_presence_checks_are_not(self):
        self.tracked(self.root, "src/lib.rs", "#[cfg(test)]\nmod tests {\n"
                     "fn helper() { assert!(result.is_ok()); }\n}\n")
        self.tracked(self.root, "src/production.rs", "assert!(result.is_ok());\n")
        self.assertEqual([x["path"] for x in self.report()["candidates"]],
                         ["src/lib.rs"])

    def test_multilanguage_candidates_have_paths_and_lines(self):
        sources = {
            "tests/a.py": "try:\n    save()\nexcept Exception:\n    pass\n",
            "tests/b.kt": "try { save() } catch (e: Exception) {}\n",
            "tests/c.swift": "XCTAssertNotNil(value)\n",
            "tests/d.ts": "expect(true).toBe(true)\n",
            "tests/e.cs": "Thread.Sleep(50);\n",
        }
        for path, text in sources.items():
            self.tracked(self.root, path, text)
        found = {x["path"]: (x["rule"], x["line"]) for x in self.report()["candidates"]}
        self.assertEqual(found, {
            "tests/a.py": ("empty-error-handler", 3),
            "tests/b.kt": ("empty-error-handler", 1),
            "tests/c.swift": ("presence-assertion", 1),
            "tests/d.ts": ("literal-tautology", 1),
            "tests/e.cs": ("sleep", 1),
        })

    def test_default_human_output_is_advisory_and_does_not_fail_on_candidates(self):
        self.tracked(self.root, "src/main.rs", "fn main() { todo!(); }\n")
        result = self.run_scan()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("1 candidate", result.stdout)
        self.assertIn("review", result.stdout.lower())
        self.assertIn("src/main.rs:1", result.stdout)

    def test_complexity_receives_only_scanned_rust_and_is_a_separate_signal(self):
        self.tracked(self.root, "src/a.rs", "fn nested() { if a { if b {} } }\n")
        self.tracked(self.root, "src/b.py", "print(1)\n")
        metric = {"files_analyzed": 1, "macro_invocations": 0, "failures": [],
                  "functions": [{"path": "src/a.rs", "name": "nested", "line": 1,
                                 "column": 1, "cyclomatic": 3, "max_nesting": 2,
                                 "macro_invocations": 0}]}
        self.complexity_helper(metric)
        data = self.report("--complexity")
        self.assertEqual(json.loads(self.capture.read_text()), [
            {"path": "src/a.rs", "source": "fn nested() { if a { if b {} } }\n"}
        ])
        self.assertEqual(data["candidate_count"], 0)
        self.assertEqual(data["complexity"]["functions"], metric["functions"])
        self.assertEqual(data["complexity"]["metric"], "syntactic-cyclomatic")

    def test_complexity_parse_failures_emit_partial_coverage_and_exit_two(self):
        self.tracked(self.root, "invalid.rs", "fn incomplete(\n")
        metric = {"files_analyzed": 0, "macro_invocations": 0, "functions": [],
                  "failures": [{"path": "invalid.rs", "error": "unexpected end"}]}
        self.complexity_helper(metric, exit_code=2)
        result = self.run_scan("--complexity", "--json")
        self.assertEqual(result.returncode, 2)
        data = json.loads(result.stdout)
        self.assertEqual(data["complexity"]["failures"], metric["failures"])
        self.assertEqual(data["complexity"]["files_requested"], 1)

    def test_complexity_cannot_claim_success_when_the_helper_omits_a_file(self):
        self.tracked(self.root, "a.rs", "fn a() {}\n")
        self.complexity_helper({"files_analyzed": 0, "macro_invocations": 0,
                                "functions": [], "failures": []})
        result = self.run_scan("--complexity", "--json")
        self.assertEqual(result.returncode, 2)
        self.assertEqual(result.stdout, "")
        self.assertIn("coverage", result.stderr.lower())

    def test_environment_cannot_select_another_complexity_executable(self):
        self.tracked(self.root, "a.rs", "fn a() {}\n")
        self.complexity_helper({"files_analyzed": 1, "macro_invocations": 0,
                                "functions": [], "failures": []})
        unexpected = Path(self.temp.name) / "unexpected-helper"
        marker = Path(self.temp.name) / "unexpected-executed"
        unexpected.write_text("#!/usr/bin/env python3\nfrom pathlib import Path\n"
                              f"Path({str(marker)!r}).touch()\nprint('bad helper')\n")
        unexpected.chmod(0o755)
        self.extra_env = {"VAUCHI_COMPLEXITY_BIN": str(unexpected)}
        self.assertEqual(self.report("--complexity")["complexity"]["files_analyzed"], 1)
        self.assertFalse(marker.exists())

    def test_scanned_workspace_cannot_select_the_executable(self):
        self.tracked(self.root, "a.rs", "struct A;\n")
        self.complexity_helper({"files_analyzed": 1, "macro_invocations": 0,
                                "functions": [], "failures": []})
        unexpected = self.root / "scripts/tools/architecture-check/target/debug/vauchi-quality-complexity"
        unexpected.parent.mkdir(parents=True)
        marker = Path(self.temp.name) / "workspace-executed"
        unexpected.write_text("#!/usr/bin/env python3\nfrom pathlib import Path\n"
                              f"Path({str(marker)!r}).touch()\nprint('wrong helper')\n")
        unexpected.chmod(0o755)
        self.assertEqual(self.report("--complexity")["complexity"]["files_analyzed"], 1)
        self.assertFalse(marker.exists())

    def test_bare_except_and_filename_substrings_have_independent_controls(self):
        self.tracked(self.root, "tests/a.py", "try:\n save()\nexcept:\n pass\n")
        self.tracked(self.root, "src/attestation.rs", "std::thread::sleep(d);\n")
        repo = self.init_repo(self.root / "test-service")
        self.tracked(repo, "src/inspector.rs", "assert!(value.is_ok());\n")
        self.assertEqual([(x["rule"], x["path"]) for x in self.report()["candidates"]],
                         [("empty-error-handler", "tests/a.py")])

    def test_reserved_repository_name_cannot_hide_workspace_coverage(self):
        self.init_repo(self.root / "root")
        result = self.run_scan("--json")
        self.assertEqual(result.returncode, 2)
        self.assertIn("Reserved repository", result.stderr)

    def test_conflict_index_entries_do_not_duplicate_scanned_files(self):
        path = "tests/conflict.rs"
        self.tracked(self.root, path, "assert!(true);\n")
        blob = self.git(self.root, "rev-parse", ":" + path)
        entries = f"0 {'0' * 40}\t{path}\n" + "".join(
            f"100644 {blob} {stage}\t{path}\n" for stage in (1, 2, 3))
        subprocess.run(["git", "-C", str(self.root), "update-index", "--index-info"],
                       input=entries, text=True, check=True)
        data = self.report()
        self.assertEqual((data["scanned_files"], data["candidate_count"]), (1, 1))

    def test_stale_or_malformed_complexity_reports_are_operational_errors(self):
        self.tracked(self.root, "a.rs", "fn a() {}\n")
        base = {"files_analyzed": 1, "macro_invocations": 0, "functions": [], "failures": []}
        cases = [{**base, "formula_version": 999},
                 {**base, "analyzed_paths": ["outside.rs"]},
                 {**base, "functions": [{"path": "a.rs", "name": "missing score"}]}]
        for response in cases:
            with self.subTest(response=response):
                self.complexity_helper(response)
                result = self.run_scan("--complexity", "--json")
                self.assertEqual(result.returncode, 2)
                self.assertEqual(result.stdout, "")
                self.assertIn("complexity", result.stderr.lower())

    def test_symlinked_installed_helper_is_rejected_before_execution(self):
        self.tracked(self.root, "a.rs", "struct A;\n")
        self.complexity_helper({"files_analyzed": 1, "macro_invocations": 0,
                                "functions": [], "failures": []})
        moved = Path(self.temp.name) / "other-helper"
        self.helper.rename(moved)
        self.helper.symlink_to(moved)
        result = self.run_scan("--complexity")
        self.assertEqual(result.returncode, 2)
        self.assertIn("symlink", result.stderr)
        self.assertFalse(self.capture.exists())


if __name__ == "__main__":
    unittest.main()
