# Sentinel regression suite for override-only-changes.sh — the
# session-end / git-wip filter that decides whether a repo's entire
# working-tree state is `just setup-path-overrides` churn (fenced
# Cargo.toml block + resulting Cargo.lock rewrite) and may therefore
# be tolerated as persistent local-dev state.
# Problem record: 2026-06-11-session-end-override-false-positives.
#
# Per CC-21 the filter must verify diff CONTENT, not filenames: a
# Cargo.toml edit outside the fence, any removal, an untracked file,
# or lock churn without an active sibling fence must all stay errors.
# Each case builds a tiny synthetic git repo, plants the state, runs
# the real script, and asserts the exit code.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SCRIPT="$SCRIPT_DIR/../override-only-changes.sh"

pass=0
fail=0

assert_exit() {
    name="$1"; want="$2"; dir="$3"
    set +e
    "$SCRIPT" "$dir" >/dev/null 2>&1
    got=$?
    set -e
    if [ "$want" = "$got" ]; then
        printf '  PASS %s\n' "$name"
        pass=$((pass + 1))
    else
        printf '  FAIL %s\n    want exit: %s\n    got exit:  %s\n' \
            "$name" "$want" "$got" >&2
        fail=$((fail + 1))
    fi
}

FENCE_BLOCK='

# >>> setup-path-overrides BEGIN — DO NOT COMMIT
# Auto-generated by: just setup-path-overrides
[patch.'"'"'https://gitlab.com/vauchi/core.git'"'"']
vauchi-core = { path = "../core/vauchi-core" }
# <<< setup-path-overrides END'

# Build a committed baseline repo: Cargo.toml + Cargo.lock at the
# given relative directory ('' = repo root, 'wasm' = nested).
make_repo() {
    sub="$1"
    repo=$(mktemp -d)
    git -C "$repo" init --quiet
    git -C "$repo" config user.email test@example.invalid
    git -C "$repo" config user.name test
    mkdir -p "$repo/${sub:-.}"
    printf '[package]\nname = "demo"\nversion = "0.1.0"\n' \
        > "$repo/${sub:+$sub/}Cargo.toml"
    printf '# lock v3\n[[package]]\nname = "demo"\nversion = "0.1.0"\n' \
        > "$repo/${sub:+$sub/}Cargo.lock"
    git -C "$repo" add -A
    git -C "$repo" commit --quiet -m baseline
    echo "$repo"
}

apply_fence() {
    printf '%s\n' "$FENCE_BLOCK" >> "$1"
}

churn_lock() {
    printf 'name = "vauchi-core"\nversion = "9.9.9"\n' >> "$1"
}

echo "override-only-changes.test.sh"

# 1. Clean tree: nothing to tolerate — not override-only.
r=$(make_repo '')
assert_exit "clean tree exits 1" 1 "$r"

# 2. Fence-only Cargo.toml addition.
r=$(make_repo '')
apply_fence "$r/Cargo.toml"
assert_exit "fence-only toml exits 0" 0 "$r"

# 3. Fence + sibling Cargo.lock churn.
r=$(make_repo '')
apply_fence "$r/Cargo.toml"
churn_lock "$r/Cargo.lock"
assert_exit "fence + lock churn exits 0" 0 "$r"

# 4. Nested workspace (web-demo wasm/ shape).
r=$(make_repo wasm)
apply_fence "$r/wasm/Cargo.toml"
churn_lock "$r/wasm/Cargo.lock"
assert_exit "nested wasm fence + lock exits 0" 0 "$r"

# 5. Staged fence (git add) is still override-only.
r=$(make_repo '')
apply_fence "$r/Cargo.toml"
git -C "$r" add -A
assert_exit "staged fence exits 0" 0 "$r"

# 6. Cargo.toml edit OUTSIDE the fence (added dependency) + fence.
r=$(make_repo '')
printf 'serde = "1"\n' >> "$r/Cargo.toml"
apply_fence "$r/Cargo.toml"
assert_exit "toml edit outside fence exits 1" 1 "$r"

# 7. Removal in Cargo.toml (deleted line) + fence.
r=$(make_repo '')
sed -i.bak '/^version/d' "$r/Cargo.toml" && rm -f "$r/Cargo.toml.bak"
apply_fence "$r/Cargo.toml"
assert_exit "toml line removal exits 1" 1 "$r"

# 8. Lock churn with NO fence in the sibling Cargo.toml.
r=$(make_repo '')
churn_lock "$r/Cargo.lock"
assert_exit "lock churn without fence exits 1" 1 "$r"

# 9. Fence + an unrelated tracked file modified.
r=$(make_repo '')
printf 'fn main() {}\n' > "$r/main.rs"
git -C "$r" add -A && git -C "$r" commit --quiet -m add-main
apply_fence "$r/Cargo.toml"
printf '// edit\n' >> "$r/main.rs"
assert_exit "fence + real file edit exits 1" 1 "$r"

# 10. Fence + an untracked file.
r=$(make_repo '')
apply_fence "$r/Cargo.toml"
printf 'scratch\n' > "$r/notes.txt"
assert_exit "fence + untracked file exits 1" 1 "$r"

# 11. Deleted Cargo.lock + fence: a missing lock is not churn.
r=$(make_repo '')
apply_fence "$r/Cargo.toml"
rm "$r/Cargo.lock"
assert_exit "deleted lock exits 1" 1 "$r"

# 12. Blank-line-only toml addition without any fence marker.
r=$(make_repo '')
printf '\n\n' >> "$r/Cargo.toml"
assert_exit "blank-only toml without fence exits 1" 1 "$r"

echo ""
echo "passed: $pass  failed: $fail"
[ "$fail" -eq 0 ]
