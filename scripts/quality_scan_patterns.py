"""Lexical review candidates; matches do not establish semantic defects."""

import re

SOURCE_EXTENSIONS = {
    ".rs", ".swift", ".kt", ".kts", ".cpp", ".cc", ".c", ".h", ".hpp",
    ".cs", ".ts", ".tsx", ".js", ".jsx", ".py", ".sh", ".bash",
}
DEPENDENCY_PARTS = {"vendor", "node_modules", "target", ".build", ".gradle", "Pods"}
GENERATED_HEADER = re.compile(
    r"automatically\s+@?generated|auto-generated|@generated|<auto-generated>", re.I
)
TEST_DIRECTORIES = {"test", "tests", "spec", "specs", "androidtest", "testfixtures"}
TEST_NAME = re.compile(r"^(?:tests?|specs?)\.|^test[_-]|[._-](?:tests?|specs?)\.[^.]+$")
CAMEL_TEST_NAME = re.compile(r"(?:Tests?|Specs?)\.[^.]+$")
INLINE_TEST = re.compile(r"#\[(?:(?:tokio|async_std)::)?test\b|#\[cfg\(test\)\]")

PATTERNS = {
    "literal-tautology": (
        r"\bassert!?\s*\(\s*true\b|\bassert\s+True\b|"
        r"\bassertTrue\s*\(\s*true\b|"
        r"\bassert_eq!\s*\(\s*(\w+)\s*,\s*\1\s*[,)]|"
        r"\bexpect\(\s*true\s*\)\.toBe\(\s*true\s*\)"
    ),
    "empty-rust-test": (
        r"#\[(?:(?:tokio|async_std)::)?test(?:\([^\]]*\))?\]\s*"
        r"(?:#\[[^\]]*\]\s*)*(?:async\s+)?fn\s+\w+\([^)]*\)\s*\{\s*\}"
    ),
    "conditional-success": r"\bif\s+let\s+(?:Ok|Some)\s*\(|\bif\s+[^\n]*\.is_(?:ok|some)\(\)",
    "presence-assertion": (
        r"assert!\([^\n;]*\.is_(?:ok|err|some)\(\)|"
        r"XCTAssertNotNil\(|\bassertNotNull\(|\.toBeDefined\(\)"
    ),
    "ignored-result": (
        r"\blet\s+_\s*=|\btry\?\s+|\.unwrap_or_default\(\)|"
        r"\.unwrap_or\((?:false|true|0|\"\"|None)\)"
    ),
    "empty-error-handler": (
        r"\bcatch\s*(?:\([^)]*\))?\s*\{\s*\}|"
        r"\bexcept\b\s*(?:Exception\s*)?:\s*(?:pass\b|return\b)"
    ),
    "test-skip": r"#\[ignore(?:\]|\()|\b(?:pytest\.skip|pytest\.mark\.skip|XCTSkip|test\.skip|it\.skip)\b",
    "placeholder": r"\b(?:todo!|unimplemented!)\s*\(|\bNotImplementedError\b",
    "sleep": (
        r"(?:std::thread::sleep|tokio::time::sleep|thread::sleep|Thread\.sleep|"
        r"time\.sleep|Task\.sleep|usleep|Thread\.Sleep)\s*\("
    ),
}
TEST_RULES = {
    "literal-tautology", "empty-rust-test", "conditional-success",
    "presence-assertion", "test-skip", "sleep",
}
RULES = {name: re.compile(pattern, re.MULTILINE) for name, pattern in PATTERNS.items()}


def candidates(text, path, scope_path=None):
    parts = (scope_path or path).split("/")
    test_like = bool(set(part.lower() for part in parts[:-1]) & TEST_DIRECTORIES
                     or TEST_NAME.search(parts[-1]) or CAMEL_TEST_NAME.search(parts[-1])
                     or INLINE_TEST.search(text))
    for name, pattern in RULES.items():
        if name in TEST_RULES and not test_like:
            continue
        for match in pattern.finditer(text):
            yield {
                "rule": name, "path": path,
                "line": text.count("\n", 0, match.start()) + 1,
                "test_like_file": test_like,
            }
