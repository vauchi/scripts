# Manages local Cargo path overrides that redirect `vauchi-core`,
# `vauchi-app`, `vauchi-protocol` and `vauchi-relay`
# from git deps to the sibling repos in the workspace.
#
# Why this script (not the previous `.cargo/config.toml` writer)?
# Modern cargo silently ignores `[patch.<source>]` in `.cargo/config.toml`
# — only `Cargo.toml` is honoured. See problem record
# `2026-05-03-cargo-path-override-broken`.
#
# The patch block is fenced with sentinel lines:
#   # >>> setup-path-overrides BEGIN — DO NOT COMMIT
#   ...
#   # <<< setup-path-overrides END
#
# A pre-commit hook blocks staging any Cargo.toml still carrying the
# fence. `clean` strips it; `check` verifies cargo picked it up.
#
# Subcommands:
#   apply  — write fenced [patch] blocks into each consumer Cargo.toml
#   clean  — strip the fenced block from each consumer Cargo.toml
#   check  — fail if any consumer still resolves vauchi-* via git
#
# Usage (called by `just setup-path-overrides` / `clean-path-overrides`
# / `check-path-overrides`):
#   bash scripts/scripts/path-overrides.sh {apply|clean|check}

set -euo pipefail

BEGIN_MARKER="# >>> setup-path-overrides BEGIN — DO NOT COMMIT"
END_MARKER="# <<< setup-path-overrides END"

# Each entry: "<consumer-dir>|<core-relative>|<relay-relative-or-empty>|<deps-csv>"
#   <consumer-dir>     repo dir relative to workspace root
#   <core-relative>    relative path FROM consumer/Cargo.toml back to ../core/
#   <relay-relative>   same, for ../relay/ (empty if consumer doesn't patch relay)
#   <deps-csv>         comma-separated set of `vauchi-core,vauchi-app,vauchi-protocol`
#                      (whichever ones this consumer depends on)
#
# web-demo/wasm is deliberately absent. It pins its core deps with an
# exact requirement (`version = "=0.55.4"`, tracking a released tag)
# rather than branch=main like the others. Cargo silently ignores a
# `[patch]` whose replacement cannot satisfy that requirement, so
# patching web-demo injected a no-op block and then reported it as a
# permanent `check` failure. Re-add it only if the exact pin is ever
# relaxed.
CONSUMERS=(
    "cli|../core||vauchi-core,vauchi-app"
    "tui|../core||vauchi-core,vauchi-app"
    "cli-display|../core||vauchi-core,vauchi-app"
    "tui-display|../core||vauchi-core,vauchi-app"
    "linux-app|../core||vauchi-core,vauchi-app"
    "relay|../core||vauchi-protocol"
    "e2e|../core|../relay|vauchi-core,vauchi-app,vauchi-protocol"
)

# ── helpers ────────────────────────────────────────────────────────────────

dep_line() {
    local dep="$1" core_rel="$2"
    case "$dep" in
        vauchi-core)     echo "vauchi-core = { path = \"$core_rel/vauchi-core\" }" ;;
        vauchi-app)      echo "vauchi-app = { path = \"$core_rel/vauchi-app\" }" ;;
        vauchi-protocol) echo "vauchi-protocol = { path = \"$core_rel/vauchi-protocol\" }" ;;
        *) echo "  ERROR: unknown dep '$dep'" >&2; exit 1 ;;
    esac
}

# Build the fenced block for one consumer. Writes to stdout.
build_block() {
    local core_rel="$1" relay_rel="$2" deps_csv="$3"
    echo "$BEGIN_MARKER"
    echo "# Auto-generated by: just setup-path-overrides"
    echo "# Strip with: just clean-path-overrides   (or git pre-commit hook)"
    echo "[patch.'https://gitlab.com/vauchi/core.git']"
    local IFS=,
    for dep in $deps_csv; do
        dep_line "$dep" "$core_rel"
    done
    if [[ -n "$relay_rel" ]]; then
        echo ""
        echo "[patch.'https://gitlab.com/vauchi/relay.git']"
        echo "vauchi-relay = { path = \"$relay_rel\" }"
    fi
    echo "$END_MARKER"
}

# Strip any existing fenced block from a Cargo.toml. Idempotent.
# Undoes exactly what append_block added — the fence and the one blank
# line before it — so apply→clean leaves the file byte-identical and git
# sees no diff.
strip_block() {
    local cargo="$1"
    [[ -f "$cargo" ]] || return 0
    grep -qF "$BEGIN_MARKER" "$cargo" || return 0
    local tmp
    tmp=$(mktemp)
    # Drop the fenced block.
    awk -v B="$BEGIN_MARKER" -v E="$END_MARKER" '
        BEGIN { skip = 0 }
        index($0, B) > 0 { skip = 1; next }
        skip == 1 && index($0, E) > 0 { skip = 0; next }
        skip == 0 { print }
    ' "$cargo" > "$tmp"
    if [[ -s "$tmp" ]] && [[ -z "$(tail -1 "$tmp")" ]]; then
        sed -e '$d' "$tmp" > "$tmp.next"
        mv "$tmp.next" "$tmp"
    fi
    mv "$tmp" "$cargo"
}

# Append the fenced block to a Cargo.toml (after first stripping any existing one).
append_block() {
    local cargo="$1" core_rel="$2" relay_rel="$3" deps_csv="$4"
    [[ -f "$cargo" ]] || { echo "  SKIP: $cargo missing"; return 0; }
    strip_block "$cargo"
    {
        echo ""
        build_block "$core_rel" "$relay_rel" "$deps_csv"
    } >> "$cargo"
}

# Delete any leftover .cargo/config.toml that contains ONLY the patch
# block (the previous, broken layout). Preserves files that have other
# settings.
remove_legacy_config() {
    local dir="$1"
    local cfg="$dir/.cargo/config.toml"
    [[ -f "$cfg" ]] || return 0
    # If file contains a [patch.] section AND nothing else of substance,
    # delete it. "Substance" = any line that isn't blank, comment, or
    # part of a [patch] section.
    local has_other
    has_other=$(awk '
        /^\[patch\./ { in_patch = 1; next }
        /^\[/        { in_patch = 0 }
        in_patch     { next }
        /^[[:space:]]*#/ { next }
        /^[[:space:]]*$/ { next }
        { print "x"; exit }
    ' "$cfg")
    if [[ -z "$has_other" ]]; then
        rm "$cfg"
        echo "  removed legacy: $cfg"
        # Also remove the .cargo dir if now empty
        rmdir "$dir/.cargo" 2>/dev/null || true
    fi
}

# ── apply ──────────────────────────────────────────────────────────────────

cmd_apply() {
    echo "── Applying local Cargo path overrides ──"
    echo ""
    for entry in "${CONSUMERS[@]}"; do
        IFS='|' read -r dir core_rel relay_rel deps_csv <<< "$entry"
        if [[ ! -d "$dir" ]]; then
            echo "  SKIP: $dir/ not present"
            continue
        fi
        local cargo="$dir/Cargo.toml"
        append_block "$cargo" "$core_rel" "$relay_rel" "$deps_csv"
        remove_legacy_config "$dir"
        echo "  $dir/Cargo.toml (patched)"

        # Refresh Cargo.lock so the patch is actually picked up. Without
        # this, `[patch]` matches by source URL but cargo continues to
        # use the locked git rev — the user sees the warning
        # "patch ... was not used in the crate graph". The lock churn
        # this produces is local-dev-only; the pre-commit hook below
        # blocks committing vauchi-* path entries in Cargo.lock.
        if [[ -f "$dir/Cargo.lock" ]]; then
            local update_args=()
            local IFS=,
            for dep in $deps_csv; do
                update_args+=(-p "$dep")
            done
            if [[ -n "$relay_rel" ]]; then
                update_args+=(-p vauchi-relay)
            fi
            unset IFS
            if (cd "$dir" && cargo update --offline "${update_args[@]}") >/dev/null 2>&1; then
                echo "  $dir/Cargo.lock (refreshed via cargo update --offline)"
            else
                echo "  $dir/Cargo.lock (cargo update failed — run manually: cargo update ${update_args[*]})"
            fi
        fi
    done
    echo ""
    echo "Done. Path overrides written to consumer Cargo.toml files."
    echo ""
    echo "Next steps:"
    echo "  - Run 'just check-path-overrides' to verify cargo picked them up."
    echo "  - Cargo.lock changes are local-dev-only — the pre-commit hook"
    echo "    blocks committing path-sourced vauchi-* entries."
    echo "  - Run 'just clean-path-overrides' before reviewing/staging Cargo.toml."
}

# ── clean ──────────────────────────────────────────────────────────────────

cmd_clean() {
    local restore_lock=0
    [[ "${1:-}" == "--restore-lock" ]] && restore_lock=1
    echo "── Stripping local Cargo path overrides ──"
    echo ""
    local stripped=0
    for entry in "${CONSUMERS[@]}"; do
        IFS='|' read -r dir _ _ _ <<< "$entry"
        local cargo="$dir/Cargo.toml"
        [[ -f "$cargo" ]] || continue
        if grep -qF "$BEGIN_MARKER" "$cargo"; then
            strip_block "$cargo"
            echo "  $cargo (stripped)"
            stripped=$((stripped + 1))
            # Stripping the fence is not enough to make the tree pullable:
            # `apply` also rewrote Cargo.lock to point at local paths, and
            # `pull --rebase --autostash` cannot pop a stashed lock over a
            # lock that main just moved. Restoring it is safe because the
            # churn is purely apply's byproduct and apply regenerates it.
            # Opt-in so plain `clean` keeps its narrower contract.
            if [[ "$restore_lock" == 1 && -f "$dir/Cargo.lock" ]] \
               && git -C "$dir" checkout HEAD -- Cargo.lock 2>/dev/null; then
                echo "  $dir/Cargo.lock (restored)"
            fi
        fi
    done
    if [[ "$stripped" == "0" ]]; then
        echo "  Nothing to strip."
    fi
    echo ""
    echo "Done."
}

# ── status ─────────────────────────────────────────────────────────────────

# Exit 0 if any consumer currently carries the fence, 1 if none do.
# Silent by design: callers branch on the exit code. `just git sync` uses
# it to decide whether to restore overrides it stripped for the pull.
cmd_status() {
    for entry in "${CONSUMERS[@]}"; do
        IFS='|' read -r dir _ _ _ <<< "$entry"
        [[ -f "$dir/Cargo.toml" ]] || continue
        if grep -qF "$BEGIN_MARKER" "$dir/Cargo.toml"; then
            return 0
        fi
    done
    return 1
}

# ── check ──────────────────────────────────────────────────────────────────

cmd_check() {
    echo "── Verifying local Cargo path overrides are live ──"
    echo ""
    local fail=0
    local ws_root
    ws_root=$(pwd -P)
    for entry in "${CONSUMERS[@]}"; do
        IFS='|' read -r dir core_rel relay_rel deps_csv <<< "$entry"
        if [[ ! -d "$dir" ]]; then continue; fi
        local cargo="$dir/Cargo.toml"
        [[ -f "$cargo" ]] || continue
        # cargo's `source: null` together with a `manifest_path` rooted in
        # the workspace means cargo resolved this dep to a sibling repo.
        # `source: "git+..."` means the patch was ignored and the
        # lock-pinned git rev is being used instead.
        local meta
        if ! meta=$(cd "$dir" && cargo metadata --format-version 1 2>/dev/null); then
            echo "  SKIP: $dir (cargo metadata failed)"
            continue
        fi
        # Build a check list: vauchi-* deps for this consumer plus relay
        # if the consumer also patches vauchi-relay.
        local checks=""
        local IFS=,
        for dep in $deps_csv; do
            checks+="$dep "
        done
        unset IFS
        if [[ -n "$relay_rel" ]]; then
            checks+="vauchi-relay "
        fi
        for dep in $checks; do
            local row
            row=$(echo "$meta" | jq -r --arg d "$dep" \
                '.packages[] | select(.name==$d) | "\(.source // "null")\t\(.manifest_path)"')
            if [[ -z "$row" ]]; then
                echo "  WARN: $dir → $dep not in dep graph"
                continue
            fi
            local src manifest
            src=${row%%	*}
            manifest=${row#*	}
            case "$src" in
                git+*)
                    echo "  FAIL: $dir → $dep is git-sourced ($src)"
                    echo "        Run: just setup-path-overrides"
                    fail=1
                    ;;
                null)
                    if [[ "$manifest" == "$ws_root"/* ]]; then
                        echo "  OK:   $dir → $dep (path: ${manifest#"$ws_root/"})"
                    else
                        echo "  WARN: $dir → $dep null source but manifest outside workspace: $manifest"
                    fi
                    ;;
                *)
                    echo "  WARN: $dir → $dep unexpected source: $src"
                    ;;
            esac
        done
    done
    echo ""
    if [[ "$fail" == "1" ]]; then
        echo "Path overrides are NOT active. Local 'cargo test/build' is reading"
        echo "whatever rev Cargo.lock pins, not your local core/ edits."
        exit 1
    fi
    echo "All consumers resolve vauchi-* via path overrides. ✓"
    echo ""
    cmd_freshness
}

# ── freshness ──────────────────────────────────────────────────────────────
#
# Path overrides redirect consumer builds to the *local* checkout of
# `core/` (and sometimes `relay/`). When that checkout is behind
# `origin/main` AND the lagging commits touch shipped code paths
# (`vauchi-*/src/`), local `just check` validates against APIs that
# differ from what CI sees — the silent break that hid Wire Humble
# Tier 0 from cli/tui until auto-vet sync exposed it on CI.
#
# This check is advisory (never exits non-zero on its own). It surfaces
# three classes:
#   OK   — at or ahead of origin/main → local matches CI
#   INFO — behind origin/main but no shipped-code drift → local matches CI
#   WARN — behind origin/main AND vauchi-*/src/ changed → CI may diverge
cmd_freshness() {
    echo "── Path-override source freshness ──"
    echo ""
    # Sources are the repos targeted by [patch] blocks. Hardcoded
    # because the workspace structure is fixed and the alternative
    # (deriving from CONSUMERS via `realpath --relative-to`) isn't
    # portable across BSD coreutils.
    local sources=("core" "relay")
    local any_drift=0
    for repo in "${sources[@]}"; do
        if [[ ! -e "$repo/.git" ]]; then
            echo "  SKIP: $repo/ (not a git repo or absent)"
            continue
        fi

        local branch head_sha behind ahead
        branch=$(git -C "$repo" symbolic-ref --short HEAD 2>/dev/null || echo "<detached>")
        head_sha=$(git -C "$repo" rev-parse --short HEAD 2>/dev/null)

        if ! git -C "$repo" rev-parse --verify -q origin/main >/dev/null 2>&1; then
            echo "  SKIP: $repo/ — no origin/main ref (run: git -C $repo fetch origin main)"
            continue
        fi

        behind=$(git -C "$repo" rev-list --count HEAD..origin/main 2>/dev/null || echo 0)
        ahead=$(git -C "$repo" rev-list --count origin/main..HEAD 2>/dev/null || echo 0)

        if [[ "$behind" -eq 0 ]]; then
            if [[ "$ahead" -gt 0 ]]; then
                echo "  OK:   $repo/ on '$branch' ($head_sha) — ${ahead} ahead, 0 behind origin/main (intentional WIP)"
            else
                echo "  OK:   $repo/ on '$branch' ($head_sha) — at origin/main"
            fi
            continue
        fi

        # Behind. Did the lagging commits touch shipped code?
        # Match any path under a workspace-member crate's src/ tree
        # (vauchi-app/src/, vauchi-core/src/, vauchi-protocol/src/,
        # vauchi-relay/src/). Test fixtures and build scripts
        # intentionally fall outside. Git pathspecs treat `vauchi-*`
        # as literal without `:(glob)` magic, and `:(glob)` itself
        # isn't portable across all shells, so post-filter with grep
        # extended-regex (POSIX, present on every dialect we support
        # — see .claude/rules/portable-shell.md).
        local critical
        critical=$(git -C "$repo" diff --name-only HEAD..origin/main 2>/dev/null \
                       | grep -E '^vauchi-[a-z]+/src/' || true)

        if [[ -z "$critical" ]]; then
            echo "  INFO: $repo/ on '$branch' ($head_sha) — ${behind} behind origin/main, no vauchi-*/src/ drift"
            continue
        fi

        any_drift=1
        local critical_count
        critical_count=$(echo "$critical" | wc -l | tr -d ' ')
        echo "  WARN: $repo/ on '$branch' ($head_sha) — ${behind} behind origin/main, ${critical_count} shipped file(s) changed:"
        echo "$critical" | head -8 | sed 's/^/          /'
        if [[ "$critical_count" -gt 8 ]]; then
            echo "          … and $((critical_count - 8)) more"
        fi
        echo "        Local 'just check' may pass on stale APIs that CI will reject."
        echo "        To test against CI's view:   git -C $repo checkout --detach origin/main"
        echo "        To update locally and stay:  git -C $repo pull --rebase --autostash"
    done
    echo ""
    if [[ "$any_drift" -eq 1 ]]; then
        echo "Drift detected (advisory only — not blocking)."
    fi
}

# ── dispatch ───────────────────────────────────────────────────────────────

case "${1:-}" in
    apply)     cmd_apply ;;
    clean)     cmd_clean "${2:-}" ;;
    check)     cmd_check ;;
    status)    cmd_status ;;
    freshness) cmd_freshness ;;
    *)
        echo "Usage: $0 {apply|clean [--restore-lock]|check|status|freshness}" >&2
        exit 2
        ;;
esac
